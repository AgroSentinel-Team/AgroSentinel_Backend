CREATE TABLE IF NOT EXISTS failure_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id BIGINT NOT NULL REFERENCES assets(id),
    user_id BIGINT NOT NULL REFERENCES usuarios(id),
    tipo_falla VARCHAR(120) NOT NULL,
    prioridad VARCHAR(16) NOT NULL CHECK (prioridad IN ('BAJA', 'MEDIA', 'ALTA', 'CRITICA')),
    descripcion TEXT NOT NULL,
    fecha_reporte TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    estado VARCHAR(16) NOT NULL CHECK (estado IN ('PENDIENTE', 'EN_REVISION', 'RESUELTO')),
    evidencia_url VARCHAR(512)
);

CREATE INDEX IF NOT EXISTS idx_failure_reports_fecha_reporte ON failure_reports (fecha_reporte DESC);
CREATE INDEX IF NOT EXISTS idx_failure_reports_asset_id ON failure_reports (asset_id);
